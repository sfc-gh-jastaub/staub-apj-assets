-- GSI TAX WORKSHOP — VALIDATION HARNESS
-- Every number the labs will quote. Run against a freshly built database.
-- =====================================================================
USE WAREHOUSE GSI_TAX_WH;
USE DATABASE GSI_TAX_WORKSHOP;

-- 1. Layer row counts and fan-out check ------------------------------
SELECT 'RAW ERP_SAP_GL'          AS OBJECT_NAME, COUNT(*)::VARCHAR AS ROW_CT FROM RAW_DATA.ERP_SAP_GL
UNION ALL SELECT 'RAW ERP_ORACLE_GL',    COUNT(*)::VARCHAR FROM RAW_DATA.ERP_ORACLE_GL
UNION ALL SELECT 'RAW ERP_LEGACY_AP',    COUNT(*)::VARCHAR FROM RAW_DATA.ERP_LEGACY_AP
UNION ALL SELECT 'CURATED rows',         COUNT(*)::VARCHAR FROM CURATED.GL_HARMONISED
UNION ALL SELECT 'CURATED distinct ids', COUNT(DISTINCT GL_LINE_ID)::VARCHAR FROM CURATED.GL_HARMONISED
ORDER BY 1;

-- 2. Conformance pass rates (Step 3 Block 3) -------------------------
SELECT COUNT(*) AS TOTAL_ROWS,
       COUNT(DISTINCT GL_LINE_ID) AS DISTINCT_LINES,
       ROUND(100.0*SUM(IFF(IS_DATE_PARSED,1,0))      /COUNT(*),2) AS PCT_DATE_OK,
       ROUND(100.0*SUM(IFF(IS_ENTITY_RESOLVED,1,0))  /COUNT(*),2) AS PCT_ENTITY_OK,
       ROUND(100.0*SUM(IFF(IS_ACCOUNT_MAPPED,1,0))   /COUNT(*),2) AS PCT_ACCOUNT_OK,
       ROUND(100.0*SUM(IFF(IS_SUPPLIER_RESOLVED,1,0))/COUNT(*),2) AS PCT_SUPPLIER_OK
FROM CURATED.GL_HARMONISED;

-- 3. Determination integrity: no fan-out, no NULL treatments ---------
SELECT COUNT(*)                                   AS DETERMINED_ROWS,
       COUNT(DISTINCT GL_LINE_ID)                 AS DISTINCT_LINES,
       COUNT_IF(TAX_TREATMENT   IS NULL)          AS NULL_TREATMENT,
       COUNT_IF(APPLIED_RATE_PCT IS NULL)         AS NULL_RATE,
       COUNT(DISTINCT APPLIED_RULE_ID)            AS RULES_FIRED
FROM TAX.V_GST_DETERMINED;

-- 4. THE HOOK: rule 9 / rule 16 either side of 1 July 2024 -----------
SELECT IFF(DOC_DATE < '2024-07-01', 'Before 1 Jul 2024', 'From 1 Jul 2024') AS PERIOD_SIDE,
       APPLIED_RULE_ID,
       TAX_TREATMENT,
       APPLIED_RATE_PCT,
       COUNT(*)                            AS GL_LINES,
       ROUND(SUM(EXPECTED_TAX_AMOUNT), 2)  AS EXPECTED_GST
FROM TAX.V_GST_DETERMINED
WHERE SUPPLY_CATEGORY = 'PROFESSIONAL_FEES'
  AND SUPPLIER_GST_REGISTERED = FALSE
  AND IS_CROSS_BORDER = TRUE
  AND JURISDICTION = 'AU'
GROUP BY 1,2,3,4 ORDER BY 1,2;

-- 5. Rules actually used, by volume ----------------------------------
SELECT APPLIED_RULE_ID, TAX_TREATMENT, COUNT(*) AS GL_LINES
FROM TAX.V_GST_DETERMINED GROUP BY 1,2 ORDER BY 3 DESC;

-- 6. BAS reconciliation status spread (Step 5 Block 1) ---------------
SELECT RECON_STATUS, COUNT(*) AS ENTITY_PERIODS,
       ROUND(MIN(VARIANCE_NET),2) AS MIN_VAR, ROUND(MAX(VARIANCE_NET),2) AS MAX_VAR
FROM TAX.V_GST_VS_BAS GROUP BY 1 ORDER BY 2 DESC;

-- 7. Exception register: every code E1-E7 must fire ------------------
SELECT COUNT(*) AS EXCEPTION_LINES,
       ROUND(100.0*COUNT(*)/2400000, 2) AS PCT_OF_LEDGER,
       COUNT_IF(EXCEPTION_CODES LIKE '%E1%') AS E1,
       COUNT_IF(EXCEPTION_CODES LIKE '%E2%') AS E2,
       COUNT_IF(EXCEPTION_CODES LIKE '%E3%') AS E3,
       COUNT_IF(EXCEPTION_CODES LIKE '%E4%') AS E4,
       COUNT_IF(EXCEPTION_CODES LIKE '%E5%') AS E5,
       COUNT_IF(EXCEPTION_CODES LIKE '%E6%') AS E6,
       COUNT_IF(EXCEPTION_CODES LIKE '%E7%') AS E7
FROM TAX.V_GST_EXCEPTIONS;

-- 8. Step 2 Block 1: the plausible wrong answer (SAP only) -----------
SELECT COUNT(DISTINCT BUKRS) AS ENTITIES_VISIBLE, COUNT(*) AS LINES_SCANNED,
       ROUND(SUM(MWSTS), 2)  AS GST_TOTAL
FROM RAW_DATA.ERP_SAP_GL
WHERE TRY_TO_DATE(BUDAT,'YYYYMMDD') >= DATEADD('month', -3, CURRENT_DATE());
